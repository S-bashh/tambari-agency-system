<?php
declare(strict_types=1);

require dirname(__DIR__) . '/app/bootstrap.php';

$configFile = TEAMS_ROOT . '/config/config.php';
session_name('TEAMS_INSTALL');
session_start();
if (empty($_SESSION['ic'])) $_SESSION['ic'] = bin2hex(random_bytes(16));

$installed = is_file($configFile);
$errors = [];
$done = false;
$manualConfig = null;

// ---- requirements ----
$req = [
    ['PHP 8.2 or newer (you have ' . PHP_VERSION . ')', version_compare(PHP_VERSION, '8.2.0', '>=')],
    ['PDO MySQL extension', extension_loaded('pdo_mysql')],
    ['mbstring extension', extension_loaded('mbstring')],
    ['GD image extension (photos)', extension_loaded('gd')],
    ['fileinfo extension (upload checks)', extension_loaded('fileinfo')],
    ['DOM extension (PDF creation)', extension_loaded('dom')],
    ['PDF library present (vendor folder)', is_file(TEAMS_ROOT . '/vendor/autoload.php')],
    ['config/ folder is writable', is_writable(TEAMS_ROOT . '/config')],
];
foreach (['documents', 'images', 'logs', 'backups', 'tmp'] as $d) {
    $req[] = ["storage/$d is writable", is_dir(TEAMS_ROOT . "/storage/$d") && is_writable(TEAMS_ROOT . "/storage/$d")];
}
$reqOk = !in_array(false, array_column($req, 1), true);

$v = ['db_host' => 'localhost', 'db_port' => '3306', 'db_name' => 'teams', 'db_user' => 'root', 'db_pass' => '',
      'admin_name' => '', 'admin_user' => 'admin', 'admin_email' => ''];

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $v = array_merge($v, array_map(fn($x) => is_string($x) ? trim($x) : '', array_intersect_key($_POST, $v)));
    $v['db_pass'] = (string)($_POST['db_pass'] ?? '');
    $pw = (string)($_POST['admin_pass'] ?? '');
    if (!hash_equals($_SESSION['ic'], (string)($_POST['_ic'] ?? ''))) $errors[] = 'Your session expired. Please reload the page and try again.';
    if (!$reqOk) $errors[] = 'Fix the failed requirements above first.';
    if (!preg_match('/^[A-Za-z0-9_]{1,60}$/', $v['db_name'])) $errors[] = 'Database name may only contain letters, numbers and underscores.';
    if (!ctype_digit($v['db_port'])) $errors[] = 'Database port must be a number.';
    if (mb_strlen($v['admin_name']) < 3) $errors[] = 'Enter the administrator\'s full name.';
    if (!preg_match('/^[A-Za-z0-9._-]{3,40}$/', $v['admin_user'])) $errors[] = 'Username must be 3-40 characters (letters, numbers, . _ -).';
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid administrator email address.';
    if ($e = Auth::validPassword($pw)) $errors[] = $e;
    if ($pw !== (string)($_POST['admin_pass2'] ?? '')) $errors[] = 'The two administrator passwords do not match.';

    if (!$errors) {
        try {
            $pdo = new PDO(sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $v['db_host'], (int)$v['db_port']), $v['db_user'], $v['db_pass'], [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION, PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            ]);
            $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . $v['db_name'] . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
            $pdo->exec('USE `' . $v['db_name'] . '`');
            $pdo->exec("SET time_zone = '+01:00'");
            if ((int)$pdo->query("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() AND table_name IN ('users','customers')")->fetchColumn() > 0) {
                $errors[] = 'The database "' . $v['db_name'] . '" already contains TEAMS tables. Choose a different database name (or see "Re-installing" in the README).';
            } else {
                $pdo->beginTransaction(); // DDL auto-commits in MySQL; the transaction only guards the data inserts below
                $pdo->commit();
                Migrator::run($pdo);
                Migrator::syncCatalogue($pdo);
                $rid = (int)$pdo->query("SELECT id FROM roles WHERE slug = 'admin'")->fetchColumn();
                $pdo->prepare('INSERT INTO users (username, full_name, email, password_hash, role_id, is_active, must_change_password) VALUES (?,?,?,?,?,1,0)')
                    ->execute([$v['admin_user'], $v['admin_name'], mb_strtolower($v['admin_email']), password_hash($pw, PASSWORD_DEFAULT), $rid]);
                $uid = (int)$pdo->lastInsertId();
                $pdo->prepare("INSERT INTO audit_logs (user_id, username, action, module, record_id, description, ip_address) VALUES (?,?,?,?,?,?,?)")
                    ->execute([$uid, $v['admin_user'], 'install', 'system', null, 'System installed (TEAMS v' . TEAMS_VERSION . ') and administrator account created', client_ip()]);

                $config = "<?php\n// Generated by the TEAMS installer on " . date('Y-m-d H:i:s') . ". Keep this file private.\nreturn " . var_export([
                    'db' => ['host' => $v['db_host'], 'port' => (int)$v['db_port'], 'name' => $v['db_name'], 'user' => $v['db_user'], 'pass' => $v['db_pass']],
                    'max_upload_mb' => 8,
                ], true) . ";\n";
                if (@file_put_contents($configFile, $config, LOCK_EX) === false) {
                    $manualConfig = $config;
                }
                $done = true;
            }
        } catch (PDOException $ex) {
            app_log('Installer: ' . $ex->getMessage());
            $code = (int)($ex->errorInfo[1] ?? 0);
            $errors[] = match ($code) {
                1045 => 'MySQL refused the username/password. In XAMPP the default user is "root" with an empty password.',
                2002 => 'Could not reach MySQL. Start MySQL in the XAMPP Control Panel and try again.',
                1044 => 'That MySQL user is not allowed to create or use this database.',
                default => 'Database error while installing (details were written to storage/logs). ' . ($code ? "MySQL code $code." : ''),
            };
        } catch (Throwable $ex) {
            app_log('Installer: ' . $ex->getMessage());
            $errors[] = 'Installation failed (details were written to storage/logs).';
        }
    }
}
